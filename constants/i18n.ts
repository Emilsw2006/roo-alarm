const fallbackLanguage: Language = 'es';

export function isLanguage(value: unknown): value is Language {
  return value === 'es' || value === 'en' || value === 'de';
}

function readPath(source: any, key: string): any {
  return key.split('.').reduce((acc, part) => (acc == null ? undefined : acc[part]), source);
}

export function translate(language: Language, key: string, params?: Record<string, string | number>): string {
  const raw = readPath(translations[language], key) ?? readPath(translations[fallbackLanguage], key) ?? key;
  if (typeof raw !== 'string') return key;
  if (!params) return raw;
  return Object.keys(params).reduce((text, paramKey) => text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(params[paramKey])), raw);
}

export function translateArray(language: Language, key: string): string[] {
  const raw = readPath(translations[language], key) ?? readPath(translations[fallbackLanguage], key);
  return Array.isArray(raw) ? [...raw] : [];
}

